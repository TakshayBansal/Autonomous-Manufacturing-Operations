def submit_supplier_certificate(
    db: Session, user: models.User, supplier_id: str, certificate_type: str,
    certificate_number: str, document_id: str | None, valid_from: str, expires_on: str,
) -> models.SupplierCertificate:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    supplier = workflows.get_scoped_or_404(db, models.Supplier, user, supplier_id, "Supplier")
    try:
        expiry = datetime.fromisoformat(expires_on).date()
        start = datetime.fromisoformat(valid_from).date() if valid_from else None
    except ValueError as exc:
        raise HTTPException(status_code=422, detail="Certificate dates must use YYYY-MM-DD") from exc
    if start and start > expiry:
        raise HTTPException(status_code=422, detail="Certificate expiry must be after its valid-from date")
    if document_id:
        workflows.get_scoped_or_404(db, models.Document, user, document_id, "Certificate document")
    previous = workflows.user_scope_query(db, models.SupplierCertificate, user).filter_by(
        supplier_id=supplier.id, certificate_type=certificate_type.strip(), status="verified",
    ).all()
    for row in previous:
        row.status = "superseded"
    certificate = models.SupplierCertificate(
        business_number=workflows.next_business_number(db, "SCERT", user),
        tenant_id=user.tenant_id, plant_id=user.plant_id, supplier_id=supplier.id,
        certificate_type=certificate_type.strip(), certificate_number=certificate_number.strip(),
        document_id=document_id, valid_from=valid_from, expires_on=expires_on,
        status="pending_review",
    )
    db.add(certificate)
    db.flush()
    supplier.status = "conditional" if supplier.status != "blocked" else supplier.status
    reviewer, reviewer_user = _membership_for_role(db, user, PURCHASE_MANAGER)
    db.add(models.Task(
        tenant_id=user.tenant_id, plant_id=user.plant_id,
        title=f"Review {certificate.certificate_type} evidence for {supplier.name}",
        owner_role=PURCHASE_MANAGER, owner_user_id=reviewer_user.id,
        owner_membership_id=reviewer.id, status="pending_approval", severity="action",
        entity_type="supplier_certificate", entity_id=certificate.id,
        due_at=utcnow() + timedelta(days=1),
        semantic_key=f"supplier-certificate-review:{certificate.id}",
        requested_outcome="Verify the evidence and record whether it is acceptable.",
    ))
    workflows.create_audit(db, user.tenant_id, user.plant_id, user.name, "supplier_certificate.submitted", "supplier_certificate", certificate.id, actor_user_id=user.id, meta={"supplier_id": supplier.id, "certificate_type": certificate_type})
    return certificate


def decide_supplier_certificate(
    db: Session, user: models.User, certificate_id: str, decision: str, notes: str,
) -> models.SupplierCertificate:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    certificate = workflows.get_scoped_or_404(db, models.SupplierCertificate, user, certificate_id, "Supplier certificate")
    if certificate.status != "pending_review":
        raise HTTPException(status_code=409, detail="Only a pending supplier certificate can be reviewed")
    certificate.status = "verified" if decision == "verify" else "rejected"
    certificate.verified_by_user_id = user.id
    certificate.verified_at = utcnow()
    certificate.review_notes = notes
    supplier = workflows.get_scoped_or_404(db, models.Supplier, user, certificate.supplier_id, "Supplier")
    capability_items = {row.item_id for row in workflows.user_scope_query(db, models.SupplierItemCapability, user).filter_by(supplier_id=supplier.id, approved=True).all()}
    readiness = workflows.supplier_compliance_readiness(db, user, supplier, capability_items)
    if supplier.status != "blocked":
        supplier.status = "approved" if readiness["eligible"] else "conditional"
    for task in workflows.user_scope_query(db, models.Task, user).filter_by(
        entity_type="supplier_certificate", entity_id=certificate.id
    ).all():
        if task.status in {"open", "accepted", "in_progress", "review", "pending_approval"}:
            task.status = "completed"
            task.completed_at = utcnow()
            task.completion_summary = f"Evidence {certificate.status}: {notes or 'review completed'}"
    workflows.create_audit(db, user.tenant_id, user.plant_id, user.name, f"supplier_certificate.{certificate.status}", "supplier_certificate", certificate.id, actor_user_id=user.id, meta={"notes": notes, "supplier_status": supplier.status})
    return certificate


def _membership_for_role(
    db: Session, user: models.User, role: str
) -> tuple[models.WorkspaceMembership, models.User]:
    membership = db.query(models.WorkspaceMembership).filter(
        models.WorkspaceMembership.tenant_id == user.tenant_id,
        models.WorkspaceMembership.default_plant_id == user.plant_id,
        models.WorkspaceMembership.role == role,
        models.WorkspaceMembership.status == "active",
    ).order_by(models.WorkspaceMembership.created_at.asc()).first()

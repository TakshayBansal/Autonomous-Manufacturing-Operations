def submit_comparison(
    db: Session, user: models.User, comparison_id: str, rationale: str
) -> models.BidComparison:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    comparison = workflows.get_scoped_or_404(db, models.BidComparison, user, comparison_id, "Comparison")
    if comparison.status not in {"draft", "ready_for_manager_review", "rejected"}:
        raise HTTPException(status_code=409, detail="Only a draft or rejected comparison can be submitted")
    if not comparison.recommended_supplier_id:
        raise HTTPException(status_code=409, detail="Select an eligible recommended supplier before submission")
    if comparison.status == "rejected":
        comparison.comparison_version += 1
    policy_result = procurement_policy.enforce_comparison(db, user, comparison, rationale)
    db.query(models.ComparisonApprovalRequest).filter_by(
        tenant_id=user.tenant_id, comparison_id=comparison.id, status="pending"
    ).update({models.ComparisonApprovalRequest.status: "invalidated"}, synchronize_session=False)
    comparison.recommendation_rationale = rationale
    comparison.status = "ready_for_approval"
    comparison.submitted_at = utcnow()
    comparison.submitted_by_user_id = user.id
    db.flush()
    artifact = generate_artifact(db, user, "comparison", comparison.id, final=True)
    for required_role in policy_result["required_approval_roles"]:
        if required_role not in {PLANT_MANAGER, PURCHASE_EXECUTIVE}:
            raise HTTPException(status_code=409, detail=f"Unsupported approval role in active procurement policy: {required_role}")
        _approval_work(db, user, comparison, artifact, required_role)
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name, "comparison.submitted",
        "bid_comparison", comparison.id, actor_user_id=user.id,
        meta={"version": comparison.comparison_version, "artifact_id": artifact.id, "policy_evaluation_id": policy_result.get("evaluation_id")},
    )
    return comparison


def decide_comparison(
    db: Session, user: models.User, comparison_id: str, decision: str, rationale: str
) -> models.BidComparison:
    require_procurement_v2(db, user)
    require_role(user, PLANT_MANAGER, PURCHASE_EXECUTIVE)
    comparison = workflows.get_scoped_or_404(db, models.BidComparison, user, comparison_id, "Comparison")
    membership = agent_service.membership_for_user(db, user)
    approval = db.query(models.ComparisonApprovalRequest).filter_by(
        tenant_id=user.tenant_id, comparison_id=comparison.id,
        comparison_version=comparison.comparison_version, required_role=user.role,
        assignee_membership_id=membership.id, status="pending",
    ).first()
    if approval is None:
        raise HTTPException(status_code=403, detail="No current named approval request is assigned to this membership")
    approval.status = "approved" if decision == "approve" else "rejected"
    approval.rationale = rationale
    approval.decided_by_user_id = user.id
    approval.decided_at = utcnow()
    tasks = db.query(models.Task).filter_by(
        tenant_id=user.tenant_id, entity_type="bid_comparison", entity_id=comparison.id,
        owner_membership_id=membership.id
    ).filter(models.Task.status.in_(["open", "pending_approval"])).all()
    for task in tasks:
        task.status = "completed"
        task.completed_at = utcnow()
    if decision == "reject":
        comparison.status = "rejected"
        db.query(models.ComparisonApprovalRequest).filter_by(
            tenant_id=user.tenant_id, comparison_id=comparison.id,
            comparison_version=comparison.comparison_version, status="pending",
        ).update({models.ComparisonApprovalRequest.status: "invalidated"}, synchronize_session=False)
        manager_membership, manager = _membership_for_role(db, user, PURCHASE_MANAGER)
        db.add(models.Task(
            tenant_id=user.tenant_id, plant_id=user.plant_id,
            title=f"Revise rejected comparison v{comparison.comparison_version}",
            owner_role=PURCHASE_MANAGER, owner_user_id=manager.id,
            owner_membership_id=manager_membership.id, status="open", severity="critical",
            due_at=utcnow() + timedelta(hours=4), entity_type="bid_comparison", entity_id=comparison.id,
        ))
    else:
        db.flush()
        pending = db.query(models.ComparisonApprovalRequest).filter_by(
            tenant_id=user.tenant_id, comparison_id=comparison.id,
            comparison_version=comparison.comparison_version, status="pending",
        ).count()
        comparison.status = "approved" if pending == 0 else "partially_approved"
        if comparison.status == "approved":
            manager_membership, manager = _membership_for_role(db, user, PURCHASE_MANAGER)
            db.add(models.Task(
                tenant_id=user.tenant_id, plant_id=user.plant_id,
                title=f"Confirm purchase order from comparison v{comparison.comparison_version}",
                owner_role=PURCHASE_MANAGER, owner_user_id=manager.id,
                owner_membership_id=manager_membership.id, status="pending_approval",
                severity="critical", due_at=utcnow() + timedelta(hours=4),
                entity_type="bid_comparison", entity_id=comparison.id,
            ))
    workflows.record_approval(
        db, user, f"bid_comparison_v{comparison.comparison_version}_{user.role}",
        comparison.id, approval.status, rationale,
    )
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name, f"comparison.{approval.status}",
        "bid_comparison", comparison.id, actor_user_id=user.id,
        meta={"version": comparison.comparison_version, "role": user.role, "rationale": rationale},
    )
    return comparison


def confirm_purchase_order(
    db: Session, user: models.User, comparison_id: str
) -> tuple[models.PODraft, models.GeneratedArtifact]:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    comparison = workflows.get_scoped_or_404(db, models.BidComparison, user, comparison_id, "Comparison")
    if comparison.status != "approved":
        raise HTTPException(status_code=409, detail="Both named comparison approvals are required before PO creation")
    row = next((item for item in comparison.rows if item.get("supplier_id") == comparison.recommended_supplier_id), None)
    if not row:
        raise HTTPException(status_code=409, detail="The approved supplier quote is unavailable")
    award = workflows.user_scope_query(db, models.AwardDecision, user).filter_by(
        rfq_id=comparison.rfq_id, supplier_id=comparison.recommended_supplier_id
    ).first()
    if award is None:
        award = models.AwardDecision(
            tenant_id=user.tenant_id, plant_id=user.plant_id,
            business_number=workflows.next_business_number(db, "AWARD", user),
            rfq_id=comparison.rfq_id, quote_id=row["quote_id"],
            supplier_id=comparison.recommended_supplier_id, status="approved",
            approved_by_user_id=user.id, approved_at=utcnow(),
            rationale=comparison.recommendation_rationale,
        )
        db.add(award)
        db.flush()
    po = workflows.create_po_draft_for_award(db, user, award)
    if po.status == "pending_approval":
        po.status = "approved_pending_outbox"
        po.approved_by_user_id = user.id
        po.approved_at = utcnow()
    artifact = generate_artifact(db, user, "po", po.id, final=True)
    existing_event = workflows.user_scope_query(db, models.IntegrationOutboxEvent, user).filter_by(
        entity_type="po_draft", entity_id=po.id, action="push_purchase_order"
    ).first()
    if existing_event is None:
        workflows.create_integration_outbox_event(
            db, user, get_settings().erp_provider or "local",
            "push_purchase_order", "po_draft", po.id, po.oracle_mapping,
            approved=False,
        )
    workflows.complete_tasks_for_entity(db, user, "bid_comparison", comparison.id)
    workflows.complete_tasks_for_entity(db, user, "po_drafts", po.id)
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name, "po.final_created",
        "po_draft", po.id, actor_user_id=user.id,
        meta={"comparison_id": comparison.id, "comparison_version": comparison.comparison_version,
              "artifact_id": artifact.id, "erp_posted": False, "supplier_sent": False},
    )
    return po, artifact


def confirm_split_purchase_orders(
    db: Session,
    user: models.User,
    comparison_id: str,
    allocations: list[dict[str, Any]],
) -> tuple[models.AwardBatch, list[models.PODraft]]:
    """Confirm one immutable allocation set and create one PO per supplier quote."""
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    comparison = workflows.get_scoped_or_404(db, models.BidComparison, user, comparison_id, "Comparison")
    if comparison.status != "approved":
        raise HTTPException(status_code=409, detail="Both named comparison approvals are required before confirming an award")
    if not allocations:
        raise HTTPException(status_code=422, detail="At least one supplier allocation is required")

    normalized = sorted(
        ({
            "rfq_line_id": str(row.get("rfq_line_id", "")),
            "quote_line_id": str(row.get("quote_line_id", "")),
            "awarded_quantity": float(row.get("awarded_quantity", 0)),
            "rationale": str(row.get("rationale", "")),
        } for row in allocations),
        key=lambda row: (row["rfq_line_id"], row["quote_line_id"]),
    )
    allocation_hash = hashlib.sha256(json.dumps(normalized, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    existing = workflows.user_scope_query(db, models.AwardBatch, user).filter_by(
        comparison_id=comparison.id, comparison_version=comparison.comparison_version,
    ).first()
    if existing:
        if existing.allocation_hash != allocation_hash:
            raise HTTPException(status_code=409, detail="This approved comparison version already has a confirmed supplier allocation")
        awards = workflows.user_scope_query(db, models.AwardDecision, user).filter_by(award_batch_id=existing.id).all()
        purchase_orders = [
            workflows.user_scope_query(db, models.PODraft, user).filter_by(award_id=award.id).one()
            for award in awards
        ]
        return existing, purchase_orders

    rfq = workflows.get_scoped_or_404(db, models.RFQ, user, comparison.rfq_id, "Supplier request")
    rfq_lines = {line.id: line for line in workflows.user_scope_query(db, models.RFQLine, user).filter_by(rfq_id=rfq.id).all()}
    rfq_totals: dict[str, float] = {}
    quote_totals: dict[str, float] = {}
    resolved: list[tuple[dict[str, Any], models.RFQLine, models.QuoteLine, models.SupplierQuote]] = []
    for row in normalized:
        if row["awarded_quantity"] <= 0:
            raise HTTPException(status_code=422, detail="Award quantities must be positive")
        rfq_line = rfq_lines.get(row["rfq_line_id"])
        if rfq_line is None:
            raise HTTPException(status_code=422, detail="An allocated line does not belong to this supplier request")
        quote_line = workflows.get_scoped_or_404(db, models.QuoteLine, user, row["quote_line_id"], "Quotation line")
        quote = workflows.get_scoped_or_404(db, models.SupplierQuote, user, quote_line.quote_id, "Quotation")
        if quote.rfq_id != rfq.id or quote.verification_status != "verified" or quote_line.rfq_line_id != rfq_line.id:
            raise HTTPException(status_code=409, detail="Every allocation must use a current verified quotation line for the selected supplier request")
        rfq_totals[rfq_line.id] = rfq_totals.get(rfq_line.id, 0) + row["awarded_quantity"]
        quote_totals[quote_line.id] = quote_totals.get(quote_line.id, 0) + row["awarded_quantity"]
        if rfq_totals[rfq_line.id] > rfq_line.quantity:
            raise HTTPException(status_code=422, detail="Allocated quantity exceeds the requested line quantity")
        if quote_totals[quote_line.id] > quote_line.quantity:
            raise HTTPException(status_code=422, detail="Allocated quantity exceeds the supplier's offered quantity")
        resolved.append((row, rfq_line, quote_line, quote))

    batch = models.AwardBatch(
        business_number=workflows.next_business_number(db, "AWARD-BATCH", user),
        tenant_id=user.tenant_id, plant_id=user.plant_id,
        comparison_id=comparison.id, comparison_version=comparison.comparison_version,
        allocation_hash=allocation_hash, status="confirmed", created_by_user_id=user.id,
        total_awarded_quantity=sum(row["awarded_quantity"] for row in normalized),
    )
    db.add(batch)
    db.flush()
    grouped: dict[tuple[str, str], list[tuple[dict[str, Any], models.RFQLine, models.QuoteLine]]] = {}
    for row, rfq_line, quote_line, quote in resolved:
        grouped.setdefault((quote.supplier_id, quote.id), []).append((row, rfq_line, quote_line))
    policy = procurement_policy.active_policy(db, user)
    if len(grouped) > 1 and not procurement_policy.policy_rules(policy).get("allow_split_awards", True):
        raise HTTPException(status_code=409, detail="The active procurement policy does not permit split supplier awards")

    purchase_orders: list[models.PODraft] = []
    for (supplier_id, quote_id), rows in grouped.items():
        award = models.AwardDecision(
            business_number=workflows.next_business_number(db, "AWARD", user),
            tenant_id=user.tenant_id, plant_id=user.plant_id, award_batch_id=batch.id,
            rfq_id=rfq.id, quote_id=quote_id, supplier_id=supplier_id, status="approved",
            approved_by_user_id=user.id, approved_at=utcnow(),
            rationale="; ".join(filter(None, (row[0]["rationale"] for row in rows))) or comparison.recommendation_rationale,
        )
        db.add(award)
        db.flush()
        for row, rfq_line, quote_line in rows:
            db.add(models.AwardLine(
                tenant_id=user.tenant_id, plant_id=user.plant_id, award_id=award.id,
                rfq_line_id=rfq_line.id, quote_line_id=quote_line.id,
                supplier_id=supplier_id, awarded_quantity=row["awarded_quantity"],
                rationale=row["rationale"],
            ))
        db.flush()
        po = workflows.create_po_draft_for_award(db, user, award)
        po.status = "approved_pending_outbox"
        po.approved_by_user_id = user.id
        po.approved_at = utcnow()
        generate_artifact(db, user, "po", po.id, final=True)
        existing_event = workflows.user_scope_query(db, models.IntegrationOutboxEvent, user).filter_by(
            entity_type="po_draft", entity_id=po.id, action="push_purchase_order",
        ).first()
        if existing_event is None:
            workflows.create_integration_outbox_event(
                db, user, get_settings().erp_provider or "local", "push_purchase_order",
                "po_draft", po.id, po.oracle_mapping, approved=False,
            )
        purchase_orders.append(po)

    workflows.complete_tasks_for_entity(db, user, "bid_comparison", comparison.id)
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name, "split_award.confirmed",
        "award_batch", batch.id, actor_user_id=user.id,
        meta={"comparison_id": comparison.id, "comparison_version": comparison.comparison_version,
              "po_ids": [po.id for po in purchase_orders], "allocation_hash": allocation_hash},
    )
    return batch, purchase_orders


def recommended_award_allocations(
    db: Session, user: models.User, comparison: models.BidComparison,
) -> list[dict[str, Any]]:
    """Resolve approved per-line recommendations into an explicit preview."""
    allocations: list[dict[str, Any]] = []
    rows = [row for row in (comparison.rows or []) if row.get("recommendation") == "Recommended" and not row.get("disqualified")]
    for row in rows:
        quote_line = workflows.get_scoped_or_404(db, models.QuoteLine, user, str(row.get("quote_line_id") or ""), "Quotation line")
        rfq_line = workflows.get_scoped_or_404(db, models.RFQLine, user, str(row.get("rfq_line_id") or quote_line.rfq_line_id or ""), "Supplier-request line")
        allocations.append({
            "rfq_line_id": rfq_line.id, "quote_line_id": quote_line.id,
            "awarded_quantity": min(float(rfq_line.quantity), float(quote_line.quantity)),
            "rationale": "Approved comparison recommendation",
            "supplier_id": str(row.get("supplier_id") or ""),
            "supplier_name": str(row.get("supplier_name") or ""),
        })
    if not allocations:
        raise HTTPException(status_code=409, detail="The approved comparison has no eligible line recommendation")
    return allocations


def prepare_po_supplier_email(
    db: Session, user: models.User, po_draft_id: str
) -> models.OutboxMessage:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    po = workflows.get_scoped_or_404(db, models.PODraft, user, po_draft_id, "PO")
    if po.status not in {"approved_pending_outbox", "simulated_posted", "posted"}:
        raise HTTPException(status_code=409, detail="Only a final purchase order can be sent")
    existing = workflows.user_scope_query(db, models.OutboxMessage, user).filter_by(
        idempotency_key=f"po:{po.id}:supplier-copy"
    ).first()
    if existing:
        return existing
    contact = workflows.user_scope_query(db, models.SupplierContact, user).filter_by(
        supplier_id=po.supplier_id
    ).first()
    if contact is None:
        raise HTTPException(status_code=409, detail="Supplier contact is required")
    # Re-evaluate the immutable snapshot before delivery. This idempotently
    # creates a corrected version for older POs whose first PDF was rendered
    # before pending lines were flushed.
    artifact = generate_artifact(db, user, "po", po.id, final=True)
    message = models.OutboxMessage(
        tenant_id=user.tenant_id, plant_id=user.plant_id, channel="email",
        recipient=contact.email, subject=f"Purchase order {po.business_number or po.id}",
        body="Please find the approved purchase order attached. Acknowledgement instructions will follow the controlled supplier workflow.",
        status="approved_pending_send", payload_hash=workflows.payload_hash(po.oracle_mapping),
        correlation_id=f"PO-MAIL-{po.id[:12]}",
        idempotency_key=f"po:{po.id}:supplier-copy",
        approved_by_user_id=user.id, approved_at=utcnow(),
        attachment_document_ids=[artifact.document_id],
        meta={"po_draft_id": po.id, "artifact_id": artifact.id},
    )
    db.add(message)
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name,
        "po.supplier_email_prepared", "po_draft", po.id,
        actor_user_id=user.id, meta={"outbox_id": message.id, "artifact_id": artifact.id},
    )
    return message


def prepare_po_change(
    db: Session, user: models.User, po_draft_id: str, change_type: str,
    reason: str, line_changes: list[dict[str, Any]], acknowledgement_id: str | None = None,
) -> models.PODraft:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    current = workflows.get_scoped_or_404(db, models.PODraft, user, po_draft_id, "Purchase order")
    if current.status not in {"posted", "simulated_posted"}:
        raise HTTPException(status_code=409, detail="Only an issued purchase order can be amended or cancelled")
    if change_type not in {"amendment", "cancellation"}:
        raise HTTPException(status_code=422, detail="Change type must be amendment or cancellation")
    root_id = current.root_po_id or current.id
    pending = workflows.user_scope_query(db, models.PODraft, user).filter(
        models.PODraft.root_po_id == root_id,
        models.PODraft.status.in_(["pending_approval", "approved_pending_outbox", "posting"]),
    ).first()
    if pending:
        raise HTTPException(status_code=409, detail="A purchase-order change is already awaiting approval or dispatch")
    receipts = workflows.user_scope_query(db, models.StoreReceipt, user).filter_by(po_draft_id=current.id).all()
    asns = workflows.user_scope_query(db, models.ASN, user).filter_by(po_draft_id=current.id).all()
    if change_type == "cancellation" and (receipts or asns):
        raise HTTPException(status_code=409, detail="An order with delivery or receipt activity cannot be cancelled; use a quantity amendment or return workflow")
    source_lines = workflows.user_scope_query(db, models.PODraftLine, user).filter_by(po_draft_id=current.id).all()
    if not source_lines:
        raise HTTPException(status_code=409, detail="Purchase order has no lines")
    changes = {str(row.get("line_id") or ""): row for row in line_changes}
    if change_type == "amendment" and not changes:
        raise HTTPException(status_code=422, detail="At least one line change is required for an amendment")
    unknown = set(changes) - {line.id for line in source_lines}
    if unknown:
        raise HTTPException(status_code=422, detail="A changed line does not belong to this purchase-order version")
    latest_version = workflows.user_scope_query(db, models.PODraft, user).filter(
        (models.PODraft.id == root_id) | (models.PODraft.root_po_id == root_id),
    ).order_by(models.PODraft.revision_number.desc()).first()
    revision_number = (latest_version.revision_number if latest_version else current.revision_number) + 1
    revision = models.PODraft(
        business_number=f"{(current.business_number or current.id).split('/V')[0]}/V{revision_number}",
        tenant_id=user.tenant_id, plant_id=user.plant_id, award_id=current.award_id,
        supplier_id=current.supplier_id, supplier_site_id=current.supplier_site_id,
        status="pending_approval", oracle_mapping=json.loads(json.dumps(current.oracle_mapping or {})),
        currency=current.currency, payment_terms=current.payment_terms,
        commercial_terms=json.loads(json.dumps(current.commercial_terms or {})),
        root_po_id=root_id, previous_version_id=current.id, revision_number=revision_number,
        revision_kind=change_type, change_reason=reason, change_summary={},
    )
    db.add(revision)
    db.flush()
    summary_lines: list[dict[str, Any]] = []
    mapped_lines: list[dict[str, Any]] = []
    for index, source in enumerate(source_lines):
        change = changes.get(source.id, {})
        quantity = float(change.get("quantity") if change.get("quantity") is not None else source.quantity)
        unit_price = float(change.get("unit_price") if change.get("unit_price") is not None else source.unit_price)
        need_by = str(change.get("need_by_date") or source.need_by_date)
        new_line = models.PODraftLine(
            tenant_id=user.tenant_id, plant_id=user.plant_id, po_draft_id=revision.id,
            award_line_id=source.award_line_id, item_id=source.item_id, quantity=quantity,
            uom=source.uom, unit_price=unit_price, gst_rate=source.gst_rate,
            need_by_date=need_by, inspection_required=source.inspection_required,
        )
        db.add(new_line)
        prior_mapping = (current.oracle_mapping.get("lines") or [{}])[index] if index < len(current.oracle_mapping.get("lines") or []) else {}
        mapped_lines.append({**prior_mapping, "quantity": quantity, "unit_price": unit_price, "need_by_date": need_by})
        if change:
            summary_lines.append({
                "source_line_id": source.id,
                "quantity": {"from": source.quantity, "to": quantity},
                "unit_price": {"from": source.unit_price, "to": unit_price},
                "need_by_date": {"from": source.need_by_date, "to": need_by},
            })
    total_received = sum(receipt.received_quantity for receipt in receipts)
    if change_type == "amendment" and sum(line["quantity"] for line in mapped_lines) < total_received:
        raise HTTPException(status_code=409, detail="Amended quantity cannot be lower than quantity already received")
    revision.oracle_mapping["lines"] = mapped_lines
    revision.oracle_mapping.update({"operation": change_type, "original_po_id": root_id, "previous_version_id": current.id, "revision_number": revision_number})
    if len(mapped_lines) == 1:
        revision.oracle_mapping.update(mapped_lines[0])
    revision.change_summary = {"type": change_type, "lines": summary_lines, "reason": reason}
    if acknowledgement_id:
        acknowledgement = workflows.get_scoped_or_404(db, models.SupplierAcknowledgement, user, acknowledgement_id, "Supplier acknowledgement")
        if acknowledgement.po_draft_id != current.id or acknowledgement.status != "change_requested":
            raise HTTPException(status_code=409, detail="Only an open supplier change request for this purchase order can be linked")
        acknowledgement.status = "change_prepared"
        acknowledgement.reviewed_by_user_id = user.id
        acknowledgement.reviewed_at = utcnow()
        acknowledgement.linked_po_revision_id = revision.id
        revision.change_summary["supplier_acknowledgement"] = acknowledgement.business_number or acknowledgement.id
        for task in workflows.user_scope_query(db, models.Task, user).filter_by(
            entity_type="supplier_acknowledgements", entity_id=acknowledgement.id
        ).filter(models.Task.status.in_(["open", "accepted", "in_progress", "review"])).all():
            task.status = "completed"
            task.completed_at = utcnow()
            task.completion_summary = f"Supplier request linked to {revision.business_number}."
    membership, manager = _membership_for_role(db, user, PURCHASE_MANAGER)
    db.add(models.Task(
        tenant_id=user.tenant_id, plant_id=user.plant_id,
        title=f"Approve PO {change_type} {(current.business_number or current.id)} v{revision_number}",
        owner_role=PURCHASE_MANAGER, owner_user_id=manager.id, owner_membership_id=membership.id,
        status="pending_approval", severity="critical", due_at=utcnow() + timedelta(hours=4),
        entity_type="po_drafts", entity_id=revision.id,
    ))
    workflows.create_audit(db, user.tenant_id, user.plant_id, user.name, f"po.{change_type}.prepared", "po_draft", revision.id, actor_user_id=user.id, meta=revision.change_summary)
    return revision


def approve_po_change(db: Session, user: models.User, revision_id: str) -> models.PODraft:
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_MANAGER, ADMIN)
    revision = workflows.get_scoped_or_404(db, models.PODraft, user, revision_id, "Purchase-order change")
    if revision.revision_kind not in {"amendment", "cancellation"} or revision.status != "pending_approval":
        raise HTTPException(status_code=409, detail="Only a pending amendment or cancellation can be approved")
    previous = workflows.get_scoped_or_404(db, models.PODraft, user, str(revision.previous_version_id or ""), "Previous purchase-order version")
    if previous.status not in {"posted", "simulated_posted"}:
        raise HTTPException(status_code=409, detail="The previous issued version is no longer current")
    revision.status = "approved_pending_outbox"
    revision.approved_by_user_id = user.id
    revision.approved_at = utcnow()
    artifact = generate_artifact(db, user, "po", revision.id, final=True)
    action = "amend_purchase_order" if revision.revision_kind == "amendment" else "cancel_purchase_order"
    workflows.create_integration_outbox_event(
        db, user, get_settings().erp_provider or "local", action, "po_draft", revision.id,
        revision.oracle_mapping, approved=False,
    )
    workflows.record_approval(db, user, "po_change", revision.id, "approved", revision.change_reason)
    workflows.complete_tasks_for_entity(db, user, "po_drafts", revision.id)
    workflows.create_audit(db, user.tenant_id, user.plant_id, user.name, f"po.{revision.revision_kind}.approved", "po_draft", revision.id, actor_user_id=user.id, meta={"previous_version_id": previous.id, "artifact_id": artifact.id, "external_dispatched": False})
    date_changes = [
        row for row in (revision.change_summary or {}).get("lines", [])
        if (row.get("need_by_date") or {}).get("from") != (row.get("need_by_date") or {}).get("to")
    ]
    if date_changes:
        from app.platform.events import DomainEvent, publish
        membership = db.query(models.WorkspaceMembership).filter_by(
            tenant_id=user.tenant_id, user_id=user.id, status="active",
        ).first()
        publish(db, DomainEvent(
            event_type="procurement.po.delivery_rescheduled", tenant_id=user.tenant_id,
            plant_id=user.plant_id, subject_type="purchase_order", subject_id=revision.id,
            actor_membership_id=membership.id if membership else None,
            payload={
                "po_revision_id": revision.id, "previous_version_id": previous.id,
                "root_po_id": revision.root_po_id or previous.id,
                "supplier_id": revision.supplier_id, "date_changes": date_changes,
                "item_ids": [line.item_id for line in db.query(models.PODraftLine).filter_by(po_draft_id=revision.id).all()],
            }, source_system="procurement",
        ))
    return revision


def prepare_supplier_followup(
    db: Session, user: models.User, rfq_id: str, supplier_id: str, body: str,
) -> models.OutboxMessage:
    """Create an idempotent, approved delivery-queue record after human confirmation."""
    require_procurement_v2(db, user)
    require_role(user, PURCHASE_EXECUTIVE, PURCHASE_MANAGER, ADMIN)
    rfq = workflows.get_scoped_or_404(db, models.RFQ, user, rfq_id, "Supplier request")
    supplier = workflows.get_scoped_or_404(db, models.Supplier, user, supplier_id, "Supplier")
    if supplier.id not in (rfq.supplier_ids or []):
        raise HTTPException(status_code=409, detail="Supplier is not included in this supplier request")
    message_body = body.strip()
    if not message_body:
        raise HTTPException(status_code=422, detail="A supplier follow-up message is required")
    contact = workflows.user_scope_query(db, models.SupplierContact, user).filter_by(
        supplier_id=supplier.id,
    ).first()
    if contact is None or not contact.email:
        raise HTTPException(status_code=409, detail="Supplier contact email is required")
    message_hash = hashlib.sha256(message_body.encode()).hexdigest()
    idempotency_key = f"rfq:{rfq.id}:supplier:{supplier.id}:followup:{message_hash[:20]}"
    existing = workflows.user_scope_query(db, models.OutboxMessage, user).filter_by(
        idempotency_key=idempotency_key,
    ).first()
    if existing:
        return existing
    message = models.OutboxMessage(
        tenant_id=user.tenant_id, plant_id=user.plant_id, channel="email",
        recipient=contact.email,
        subject=f"Follow-up on supplier request {rfq.business_number or rfq.id}",
        body=message_body, status="approved_pending_send", payload_hash=message_hash,
        correlation_id=f"RFQ-FOLLOWUP-{rfq.id[:10]}-{supplier.id[:8]}",
        idempotency_key=idempotency_key, approved_by_user_id=user.id,
        approved_at=utcnow(), attachment_document_ids=[],
        meta={"rfq_id": rfq.id, "supplier_id": supplier.id, "message_type": "supplier_followup"},
    )
    db.add(message)
    workflows.create_audit(
        db, user.tenant_id, user.plant_id, user.name,
        "rfq.supplier_followup_prepared", "rfq", rfq.id,
        actor_user_id=user.id, meta={"supplier_id": supplier.id, "outbox_id": message.id},
    )
    return message
